import * as fs from 'fs';
import { Spc700 } from './src/emulator/audio/Spc700';
import { Apu } from './src/emulator/audio/Apu';

const apu = new Apu();
const spc = apu.spc;

const spcRam = new Uint8Array([
0x8f, 0xaa, 0xf4, 0x8f, 0xbb, 0xf5, 0xe8, 0xcc, 0xfa, 0xf4, 0xef, 0x69, 0xf4, 0xef, 0xd0, 0xf8,
0x2e, 0xef, 0xf5, 0xe4, 0xef, 0xfa, 0xf6, 0x3d, 0xfa, 0xf7, 0x3e, 0xfd, 0xe4, 0xf5, 0xcb, 0xf4,
0xd0, 0x08, 0x8f, 0xb0, 0xf1, 0xcb, 0xf5, 0x5f, 0x00, 0x07, 0xcd, 0x00, 0x7d, 0xfa, 0xf4, 0xef,
0x69, 0xf4, 0xef, 0xd0, 0xf8, 0x2e, 0xef, 0xf5, 0xe4, 0xf5, 0xd8, 0xf4, 0xd5, 0x40, 0x85, 0x7d,
0x3d, 0xd0, 0x02, 0xab, 0x3e, 0xfa, 0xf4, 0xef, 0x69, 0xf4, 0xef, 0xd0, 0xf8, 0x64, 0xef, 0xf0
]);

for (let i = 0; i < spcRam.length; i++) {
    (spc as any).ram[i] = spcRam[i];
}

spc.state.pc = 0x0000;
spc.state.a = 0;
spc.state.x = 0;
spc.state.y = 0;
spc.state.sp = 0xEF;

for (let i = 0; i < 50; i++) {
    const pc = spc.state.pc;
    const op = (spc as any).ram[pc];
    console.log(`PC=${pc.toString(16).padStart(4, '0')} OP=${op?.toString(16).padStart(2, '0')} A=${spc.state.a.toString(16).padStart(2, '0')} X=${spc.state.x.toString(16).padStart(2, '0')} Y=${spc.state.y.toString(16).padStart(2, '0')} SP=${spc.state.sp.toString(16)}`);
    
    if (pc === 0x0008) (spc as any).ram[0xF4] = spc.state.a;
    if (pc === 0x002D) (spc as any).ram[0xF4] = spc.state.a;
    if (pc === 0x0045) (spc as any).ram[0xF4] = spc.state.a;

    spc.state.pc++;
    const taken = spc.executeOpcode(op);
    if (taken === undefined || isNaN(taken)) {
        console.error('Undefined taken at op', op?.toString(16));
        break;
    }
}
