import re

opcodes = ['0x0b', '0x0c', '0x0e', '0x17', '0x36', '0x37', '0x3b', '0x3c', '0x47', '0x4e', '0x58', '0x59', '0x5a', '0x66', '0x67', '0x6a', '0x74', '0x76', '0x7f', '0x85', '0x86', '0x87', '0x8a', '0x94', '0x97', '0x98', '0x99', '0x9f', '0xa5', '0xa6', '0xa9', '0xb5', '0xb6', '0xb9', '0xbb', '0xed']

with open("mame_spc.cpp", "r") as f:
    text = f.read()

# find definitions like `case 0x0b:` and read the line
lines = text.split("\n")
for op in opcodes:
    op_int = int(op, 16)
    pattern = f"case 0x{op_int:02x}:"
    for i, line in enumerate(lines):
        if pattern in line:
            print(f"{op}: {line.strip()} {lines[i+1].strip()}")
            break
